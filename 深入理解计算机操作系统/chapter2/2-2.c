#include <stdio.h>

int main()
{
    printf("2的11次幂,十进制: %d, 十六进制: 0x%X\n", 2 << (11 - 1), 2 << (11 - 1));
    printf("2的7次幂,十进制: %d, 十六进制: 0x%X\n", 2 << (7 - 1), 2 << (7 - 1));
    printf("2的13次幂, 十进制: %d, 十六进制: 0x%X\n", 2 << (13 - 1), 2 << (13 - 1));
    printf("0x2000的十进制: %d\n", 0x2000);
    printf("2的16次幂,十进制: %d, 十六进制: 0x%X\n", 2 << (16 - 1), 2 << (16 - 1));
    printf("0x20的十进制: %d  是多少次幂: %d\n", 0x20, 5);
}
